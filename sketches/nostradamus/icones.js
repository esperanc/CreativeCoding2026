function iconeSVG(largura, altura, retangulos, escala = 3) {
  const rects = retangulos.map(([x, y, w = 1, h = 1, cor = '#1a1a1a']) =>
    `<rect x="${x}" y="${y}" width="${w}" height="${h}" fill="${cor}"/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${largura * escala}" height="${altura * escala}"
    viewBox="0 0 ${largura} ${altura}" shape-rendering="crispEdges">${rects}</svg>`;
}


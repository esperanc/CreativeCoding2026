// ============================================================
// FUNÇÃO AUXILIAR PARA DESENHAR QUADRILÁGULOS
// ============================================================
//
// Em vez de escrever repetidamente:
//
// quad(...);
//
// criamos uma função chamada q().
//
// Assim:
//
// q(x1,y1,x2,y2,x3,y3,x4,y4);
//
// continua utilizando internamente a única primitiva
// geométrica permitida: quad().
// ============================================================

function q(x1, y1, x2, y2, x3, y3, x4, y4) {
  quad(
    x1, y1,
    x2, y2,
    x3, y3,
    x4, y4
  );
}



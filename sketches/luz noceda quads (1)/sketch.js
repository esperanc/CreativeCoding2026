/*
 * ============================================================
 * REINTERPRETAÇÃO GEOMÉTRICA DE UMA PERSONAGEM
 * ============================================================
 *
 * Este programa foi feito em p5.js.
 *
 * OBJETIVO:
 * Recriar, de maneira estilizada, a personagem da imagem
 * utilizando SOMENTE a primitiva geométrica QUAD.
 *
 * A função quad() desenha um quadrilátero a partir de quatro
 * pontos:
 *
 *     quad(x1, y1, x2, y2, x3, y3, x4, y4);
 *
 * Cada quadrilátero possui quatro vértices.
 *
 * Não utilizamos:
 *   ellipse()
 *   rect()
 *   triangle()
 *   line()
 *   arc()
 *   beginShape()
 *   vertex()
 *
 * Todas as partes da ilustração são construídas com vários
 * quadriláteros sobrepostos.
 *
 * ============================================================
 */


// ------------------------------------------------------------
// CONFIGURAÇÃO DA TELA
// ------------------------------------------------------------

function setup() {
  createCanvas(800, 800);

  // Desenharemos tudo uma única vez.
  // Portanto, não existe animação.
  noLoop();

  // O desenho fica mais bonito sem suavização excessiva
  // das bordas dos quadriláteros.
  smooth();
}



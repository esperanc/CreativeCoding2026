function setup() {
  // Cria uma área de desenho com 800 pixels de largura
  // e 600 pixels de altura.
  createCanvas(800, 600);

  // Como o desenho é estático, noLoop() impede que o p5.js
  // fique redesenhando a cena continuamente.
  noLoop();
}

